export function getThemeDisplay(
  theme: ThemeConfig,
  lang: AppLanguage,
): { name: string; subtitle: string } {
  if (lang === 'ko') {
    return { name: theme.name, subtitle: theme.subtitle };
  }
  return {
    name: THEME_NAME_EN[theme.id] ?? theme.name,
    subtitle: THEME_SUBTITLE_EN[theme.id] ?? theme.subtitle,
  };
}

