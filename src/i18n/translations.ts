import { AppLanguage, DifficultySpeed, FontId, ThemeConfig, ThemeId } from '../types/game';

export function formatTimeUnit(seconds: number, lang: AppLanguage): string {
  return lang === 'en' ? `${seconds}s` : `${seconds}초`;
}

export function formatSpeedUnit(speed: number, lang: AppLanguage): string {
  return lang === 'en' ? `${speed} CPM` : `${speed}타`;
}

export function getDifficultyTierLabel(speed: DifficultySpeed, lang: AppLanguage): string {
  if (lang === 'en') {
    switch (speed) {
      case 200:
        return 'Beginner';
      case 400:
        return 'Normal';
      case 600:
        return 'Fast';
      case 800:
        return 'Extreme';
    }
  }
  switch (speed) {
    case 200:
      return '초급';
    case 400:
      return '보통';
    case 600:
      return '빠름';
    case 800:
      return '최고속';
  }
}

export function getDisplayRank(rank: string, lang: AppLanguage): string {
  if (lang === 'en' && rank === 'L을가져가') {
    return 'Take the L';
  }
  return rank;
}

